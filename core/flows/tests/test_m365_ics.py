def test_unfolding_is_a_precondition_not_a_nicety():
    """Un-unfolded, the join URL is split across physical lines and matches truncated."""
    raw_hits = rig._TEAMS_URL.findall(MICROSOFT_INVITE)
    unfolded_hits = rig._TEAMS_URL.findall(rig.unfold_ics(MICROSOFT_INVITE))
    assert JOIN not in raw_hits
    assert JOIN in unfolded_hits


def test_location_never_carries_the_join_url():
    """The single most likely wrong guess a parser author makes."""
    assert "LOCATION" not in rig.ics_teams_evidence(MICROSOFT_INVITE)["join_urls"]
    assert "LOCATION" not in rig.ics_teams_properties(MICROSOFT_INVITE)


def test_description_first_match_is_the_wrong_id():
    urls = rig.ics_teams_evidence(MICROSOFT_INVITE)["join_urls"]["DESCRIPTION"]
    assert rig.teams_native_id(urls[0]) == ("teams", "373241627805208")
    assert rig.teams_native_id(urls[-1]) == ("teams", THREAD)


def test_thread_id_comes_from_the_json_property_without_url_parsing():
    ev = rig.ics_teams_evidence(MICROSOFT_INVITE)
    assert ev["thread_id"] == THREAD
    assert ev["online_meeting_provider"] == 3  # teamsForBusiness


def test_x_property_is_the_canonical_url_and_parses_to_the_thread_id():
    props = rig.ics_teams_properties(MICROSOFT_INVITE)
    assert props["X-MICROSOFT-SKYPETEAMSMEETINGURL"] == JOIN
    assert rig.teams_native_id(props["X-MICROSOFT-SKYPETEAMSMEETINGURL"]) == ("teams", THREAD)


def test_description_url_stops_at_the_escaped_newline():
    """`\\n` inside an ICS TEXT value is a literal backslash-n; a URL character class that
    allows backslashes runs past the link into the next line's prose."""
    first = rig.ics_teams_evidence(MICROSOFT_INVITE)["join_urls"]["DESCRIPTION"][0]
    assert first.endswith("?p=HspUEOnQK2jxCFVGhg")
    assert "\\" not in first


def test_summary_reports_method_and_uid():
    s = rig.summarize_ics(MICROSOFT_INVITE)
    assert s["method"] == "REQUEST"
    assert s["dtstart"] == "20260824T162446Z"
    assert "X-MICROSOFT-SKYPETEAMSMEETINGURL" in s["properties"]


def test_non_teams_input_is_reported_as_absent_not_guessed():
    assert rig.ics_teams_evidence("") == {}
    assert rig.ics_teams_evidence("BEGIN:VCALENDAR\r\nEND:VCALENDAR\r\n") == {}
    assert rig.teams_native_id("https://meet.google.com/abc-defg-hij") is None
    assert rig.teams_native_id("") is None


def test_rfc2047_subject_decoding():
    """Exchange encodes any subject with a non-ASCII character; an em dash suffices."""
    assert rig.decode_header_text(
        "=?Windows-1252?Q?Vexa_rig_=97_ICS_property_probe?=") == "Vexa rig — ICS property probe"
    assert rig.decode_header_text("plain subject") == "plain subject"


def test_mime_calendar_parts_finds_the_text_calendar_body():
    mime = ("From: a@b.c\r\nTo: d@e.f\r\nSubject: x\r\n"
            "Content-Type: multipart/alternative; boundary=\"B\"\r\nMIME-Version: 1.0\r\n\r\n"
            "--B\r\nContent-Type: text/plain\r\n\r\nhello\r\n"
            "--B\r\nContent-Type: text/calendar; method=REQUEST\r\n\r\n"
            + MICROSOFT_INVITE + "\r\n--B--\r\n")
    parts = rig.mime_calendar_parts(mime)
    assert len(parts) == 1
    assert rig.ics_teams_evidence(parts[0])["thread_id"] == THREAD
