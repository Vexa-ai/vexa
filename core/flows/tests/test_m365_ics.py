def test_unfolding_is_a_precondition_not_a_nicety():
    """Un-unfolded, the join URL is split across physical lines and matches truncated."""
    assert JOIN not in outlook._TEAMS_URL.findall(MICROSOFT_INVITE)
    assert JOIN in outlook._TEAMS_URL.findall(outlook.unfold_ics(MICROSOFT_INVITE))


def test_location_never_carries_the_join_url():
    """The single most likely wrong guess a parser author makes."""
    assert "LOCATION" not in outlook.ics_teams_evidence(MICROSOFT_INVITE)["join_urls"]
    assert "LOCATION" not in outlook.ics_teams_properties(MICROSOFT_INVITE)


def test_description_first_match_is_the_wrong_id():
    urls = outlook.ics_teams_evidence(MICROSOFT_INVITE)["join_urls"]["DESCRIPTION"]
    assert outlook.teams_native_id(urls[0]) == ("teams", "373241627805208")
    assert outlook.teams_native_id(urls[-1]) == ("teams", THREAD)


def test_thread_id_comes_from_the_json_property_without_url_parsing():
    ev = outlook.ics_teams_evidence(MICROSOFT_INVITE)
    assert ev["thread_id"] == THREAD
    assert ev["online_meeting_provider"] == 3         # teamsForBusiness


def test_x_property_is_the_canonical_url_and_parses_to_the_thread_id():
    props = outlook.ics_teams_properties(MICROSOFT_INVITE)
    assert props["X-MICROSOFT-SKYPETEAMSMEETINGURL"] == JOIN
    assert outlook.teams_native_id(props["X-MICROSOFT-SKYPETEAMSMEETINGURL"]) == ("teams", THREAD)


def test_description_url_stops_at_the_escaped_newline():
    """`\\n` inside an ICS TEXT value is a literal backslash-n; a URL character class that allows
    backslashes runs past the link into the next line's prose."""
    first = outlook.ics_teams_evidence(MICROSOFT_INVITE)["join_urls"]["DESCRIPTION"][0]
    assert first.endswith("?p=HspUEOnQK2jxCFVGhg")
    assert "\\" not in first


def test_the_products_own_teams_pattern_stops_there_too():
    """Not only the evidence reader: `mailbox.TEAMS_URL` is what admits a Teams invite, and it
    used to allow `\\` in the path. THIS is the assertion that pins the fix in the shipped code."""
    hit = TEAMS_URL.search(outlook.unfold_ics(MICROSOFT_INVITE))
    assert hit is not None
    assert "\\" not in hit.group(0)


def test_non_teams_input_is_reported_as_absent_not_guessed():
    assert outlook.ics_teams_evidence("") == {}
    assert outlook.ics_teams_evidence("BEGIN:VCALENDAR\r\nEND:VCALENDAR\r\n") == {}
    assert outlook.teams_native_id("https://meet.google.com/abc-defg-hij") is None
    assert outlook.teams_native_id("") is None
    assert outlook.teams_join_url("BEGIN:VCALENDAR\r\nEND:VCALENDAR\r\n") is None


def test_rfc2047_subject_decoding():
    """Exchange encodes any subject with a non-ASCII character; an em dash suffices."""
    assert outlook.decode_header_text(
        "=?Windows-1252?Q?Vexa_rig_=97_ICS_property_probe?=") == "Vexa rig \u2014 ICS property probe"
    assert outlook.decode_header_text("plain subject") == "plain subject"


# ── and now the product, end to end over the real invitation ─────────────────────────────────
def test_the_parser_admits_the_canonical_url_not_the_first_one_it_sees():
    """THE PORT'S POINT. `parse_ics` scans the event top-to-bottom; on this invitation that order
    is LOCATION (prose), then DESCRIPTION (the short-form id), then the X- property. Without the
    Microsoft-first rule the admitted URL is `/meet/373241627805208` — a different identifier for
    the same meeting, admitted with no error, and a bot dispatched at nothing."""
    ev = parse_ics(MICROSOFT_INVITE, "info@vexa.ai")
    assert ev is not None
    assert ev["url"] == JOIN
    assert outlook.teams_native_id(ev["url"]) == ("teams", THREAD)
    assert ev["organizer"] == "organizer@example.onmicrosoft.com"
    # `SUMMARY;LANGUAGE=en-US:` — `^SUMMARY:` matched nothing, so every Exchange invite was
    # titled "Meeting", and that title is the subject line of the mail we send back.
    assert ev["title"] == "Vexa rig probe"


def test_the_generic_scan_alone_would_have_taken_the_wrong_link():
    """The counter-proof, so the assertion above cannot pass for the wrong reason."""
    from flows_integrations.mailbox import _meeting_url
    generic = _meeting_url(outlook.unfold_ics(MICROSOFT_INVITE))
    assert generic is not None
    assert outlook.teams_native_id(generic) == ("teams", "373241627805208")
    assert generic != JOIN
