"""The Microsoft-ICS reading rules, pinned offline.

Every byte of MICROSOFT_INVITE below was captured from a REAL invitation composed by a
real Microsoft 365 tenant on 2026-08-24 (rig: `witness/m365_rig.py invite send` →
`gmail poll`), with the tenant/organizer GUIDs and the passcode replaced. It is folded at
75 octets exactly as Exchange folded it, because the folding is half of what these tests
are defending against.

The three findings these tests exist to keep true:

  1. LOCATION is the string "Microsoft Teams Meeting" — it NEVER carries the join URL.
  2. DESCRIPTION carries TWO different links, and the FIRST one is the short-form
     `/meet/<digits>` id, not the `19:meeting_…@thread.v2` the meeting-api wants.
  3. X-MICROSOFT-SKYPETEAMSPROPERTIES.cid carries the thread id already decoded, so the
     correct parser reads a JSON field and does no URL parsing at all.
"""
