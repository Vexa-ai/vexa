    "X-MICROSOFT-LOCATIONS:[{\"DisplayName\":\"Microsoft Teams Meeting\"\\,\"LocationUri\r\n"
    " \":\"\"}]\r\n"
    "X-MICROSOFT-DISALLOW-COUNTER:FALSE\r\n"
    "END:VEVENT\r\n"
