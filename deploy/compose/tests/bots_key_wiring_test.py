"""The broker's bots role key reaches meeting-api and the broker only (offline — no stack, no docker).

meeting-api keeps bot accounts (saved signed-in browser profiles, ADR-0049) in the credential broker,
signing as the `bots` role. The key reads every bot account's profile, so it is generated by
`connections-keys`, mounted by the broker and meeting-api, and by no other service; meeting-api joins
the internal `connections` network to reach the broker.
"""
from __future__ import annotations

import re

from workspace_store_wiring_test import COMPOSE, _service

KEY_MOUNT = re.compile(r"^\s+- connections-bots-key:", re.M)


def test_connections_keys_generates_the_bots_key():
    block = _service("connections-keys")
    assert '"bots"' in block and KEY_MOUNT.search(block)


def test_the_broker_and_meeting_api_mount_the_bots_key():
    broker = _service("credential-broker")
    assert "VEXA_CONNECTIONS_BOTS_KEY_FILE=/run/vexa-connections/bots/key" in broker
    assert "- connections-bots-key:/run/vexa-connections/bots:ro" in broker
    meeting = _service("meeting-api")
    assert "VEXA_BOT_ACCOUNTS_KEY_FILE=/run/vexa-connections/bots/key" in meeting
    assert "VEXA_BOT_ACCOUNTS_BROKER_URL=${VEXA_BOT_ACCOUNTS_BROKER_URL-http://credential-broker:8100}" in meeting
    assert "- connections-bots-key:/run/vexa-connections/bots:ro" in meeting
    assert re.search(r"^\s+networks: \[[^\]]*\bconnections\b", meeting, re.M)


def test_no_other_service_mounts_the_bots_key():
    names = re.findall(r"^  ([a-z0-9-]+):$", COMPOSE.read_text().split("\nvolumes:", 1)[0], re.M)
    holders = {n for n in names if KEY_MOUNT.search(_service(n))}
    assert holders == {"connections-keys", "credential-broker", "meeting-api"}
